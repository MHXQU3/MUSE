#!/usr/bin/env python3
"""Write dev/seed_test_history.sql: invented listening history generated
inside Postgres, for trying the website before your real export arrives.

It uses the same invented catalogue as generate_test_export.py, creates about
four years of plays with SQL's random(), and loads them through the real
import pipeline (import_staging -> process_import_batch). It then fills in
countries and languages for the invented artists, standing in for
MusicBrainz. Everything lands in one import batch marked 'test_data', so
`python -m muse_import rollback <batch id>` removes the plays again.

    python scripts/make_test_sql.py
    # then run dev/seed_test_history.sql in the Supabase SQL editor,
    # after replacing YOUR_EMAIL with your account's email.
"""

import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "scripts"), str(ROOT / "importer")]

from generate_test_export import ARTISTS, build_catalogue  # noqa: E402
from muse_import.parse import detect_version, featured_artists  # noqa: E402

LANG = {"us_hiphop": "eng", "other": "eng", "fr_rap": "fra", "es_urban": "spa", "north_africa": "ara"}


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def arr(items) -> str:
    return "array[" + ",".join(q(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def main() -> None:
    tracks = build_catalogue(random.Random(7))
    rows = ",\n    ".join(
        f"({q(t['uri'])},{q(t['title'])},{q(t['artist'])},{q(t['album'])},{q(t['scene'])},"
        f"{t['duration_ms']},{t['popularity']:.3f},{q(detect_version(t['title']))},{arr(featured_artists(t['title']))})"
        for t in tracks)
    countries = ",\n    ".join(f"({q(a)},{q(c)},{q(LANG[s])})" for a, c, s in ARTISTS)

    sql = f"""-- Invented listening history for trying MUSE. Generated by scripts/make_test_sql.py.
-- Replace YOUR_EMAIL below, then run once. Undo with:
--   python -m muse_import rollback <batch id>   (shown by `python -m muse_import batches`)
do $muse$
declare
  v_user  uuid := (select id from auth.users where lower(email) = lower('YOUR_EMAIL'));
  v_batch uuid := gen_random_uuid();
  v_stats jsonb;
begin
  if v_user is null then
    raise exception 'No user with that email. Add yourself in Authentication > Users first.';
  end if;
  perform setseed(0.42);

  create temp table cat (uri text, title text, artist text, album text, scene text,
                         dur int, pop real, version_type text, feat text[]) on commit drop;
  insert into cat values
    {rows};

  -- Cumulative weights per scene, for weighted random picks.
  create temp table cat_cum on commit drop as
    select *, sum(0.05 + pop) over (partition by scene order by uri) - (0.05 + pop) as lo,
              sum(0.05 + pop) over (partition by scene order by uri) as hi,
              sum(0.05 + pop) over (partition by scene) as total
    from cat;

  insert into import_batches (id, user_id, source, file_names, stats)
  values (v_batch, v_user, 'test_data', array['generated in the database'],
          jsonb_build_object('note', 'invented test data'));

  with days as (
    select d::date as d from generate_series('2023-01-01'::date, '2026-10-31'::date, interval '1 day') d
  ), sessions as (
    select d, s,
           d + make_interval(hours => (array[7,8,12,17,18,19,21,22,23])[1 + floor(random() * 9)::int],
                             mins => floor(random() * 60)::int) as start_at,
           4 + floor(random() * 15)::int as n
    from days cross join generate_series(1, 3) s
    where random() < case when extract(isodow from d) >= 6 then 0.6 else 0.45 end
                     + case when extract(month from d) in (7, 12) then 0.2 else 0 end
  ), plays as (
    select se.d, se.s, se.start_at, i, random() as r_scene, random() as r_track,
           random() as r_skip, (500 + floor(random() * 3500))::int as gap
    from sessions se cross join lateral generate_series(1, se.n) i
  ), scened as (
    select p.*,
      case extract(year from p.d)::int
        when 2023 then case when r_scene < .70 then 'us_hiphop' when r_scene < .82 then 'fr_rap'
                            when r_scene < .87 then 'es_urban' when r_scene < .90 then 'north_africa' else 'other' end
        when 2024 then case when r_scene < .25 then 'us_hiphop' when r_scene < .80 then 'fr_rap'
                            when r_scene < .88 then 'es_urban' when r_scene < .93 then 'north_africa' else 'other' end
        when 2025 then case when r_scene < .10 then 'us_hiphop' when r_scene < .35 then 'fr_rap'
                            when r_scene < .70 then 'es_urban' when r_scene < .95 then 'north_africa' else 'other' end
        else           case when r_scene < .12 then 'us_hiphop' when r_scene < .42 then 'fr_rap'
                            when r_scene < .67 then 'es_urban' when r_scene < .92 then 'north_africa' else 'other' end
      end as scene
    from plays p
  ), picked as (
    select sc.*, c.uri, c.title, c.artist, c.album, c.version_type, c.feat,
           case when sc.r_skip < 0.18 then floor(sc.r_skip / 0.18 * 35000)::int else c.dur end as ms
    from scened sc
    join cat_cum c on c.scene = sc.scene and sc.r_track * c.total >= c.lo and sc.r_track * c.total < c.hi
  ), timed as (
    select *, start_at + make_interval(secs => sum(ms + gap) over (partition by d, s order by i) / 1000.0) as ended_at
    from picked
  )
  insert into import_staging (batch_id, row_num, ended_at, ms_played, track_name, artist_name, album_name,
                              spotify_track_uri, reason_start, reason_end, shuffle, skipped, offline,
                              incognito, version_type, featured_artists)
  select v_batch, row_number() over (order by ended_at), ended_at at time zone 'Europe/London', ms,
         title, artist, album, uri, 'trackdone',
         case when r_skip < 0.18 then 'fwdbtn' else 'trackdone' end,
         r_track < 0.4, r_skip < 0.18, false, false, version_type, feat
  from timed;

  v_stats := process_import_batch(v_batch);

  -- Stand-in for MusicBrainz: the invented artists' countries and languages.
  update artists a set country = v.country, metadata_source = 'test_seed', enriched_at = now()
  from (values
    {countries}) v(name, country, lang)
  where a.name = v.name;
  update tracks t set language = v.lang, language_source = 'test_seed'
  from artists a, (values
    {countries}) v(name, country, lang)
  where a.id = t.primary_artist_id and a.name = v.name;

  raise notice 'Test history loaded: batch %, %', v_batch, v_stats;
end
$muse$;
"""
    out = ROOT / "dev" / "seed_test_history.sql"
    out.write_text(sql)
    print(f"wrote {out} ({len(sql) / 1000:.0f} KB, {len(tracks)} tracks)")


if __name__ == "__main__":
    main()
